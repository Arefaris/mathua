'use client'

import Link from 'next/link'
import SectionHeader from './SectionHeader'
import DocsMarkdown from './DocsMarkdown'
import TableOfContents from './TableOfContents'
import { TOC_MIN_HEADINGS } from '../lib/docsToc'
import docs from '../content/docs.generated.json'
import { useT } from '../lib/i18n'
import type { MessageKey } from '../lib/i18n/keys'

// The shell every rendered documentation page shares: a back link, the heading, a table of
// contents for a long document, and the body built from the repository markdown. The pages
// themselves are one line each.
//
// The content is generated by scripts/build-docs.mjs into content/docs.generated.json, so the
// page and the repo doc are one text. A "Source" link goes back to the file it came from.

const monoFont = "var(--font-jetbrains-mono), 'JetBrains Mono', monospace"
const REPO_BLOB = 'https://github.com/chuma-beep/mathua/blob/main/'

type DocEntry = {
  title: string
  description: string
  source: string
  body: string
  headings: { id: string; text: string; level: number }[]
}

export default function DocPage({
  slug,
  labelKey = 'shell.docPage.docs',
}: {
  slug: string
  labelKey?: MessageKey
}) {
  const t = useT()
  const doc = (docs as Record<string, DocEntry>)[slug]
  if (!doc) return null

  // A table of contents earns its sidebar only on a document long enough to need one. A page
  // with two or three sections reads top to bottom faster than it can be navigated.
  const showToc = doc.headings.length >= TOC_MIN_HEADINGS

  return (
    <div className="max-w-container mx-auto px-4 sm:px-6 pb-[calc(80px+env(safe-area-inset-bottom))] lg:pb-0 overflow-x-hidden min-w-0">
      <Link
        href="/docs"
        className="inline-block mt-8"
        style={{ fontFamily: monoFont, fontSize: '13px', color: 'var(--text-muted)' }}
      >
        {t('shell.docPage.back')}
      </Link>
      <section className="pt-8 min-w-0 overflow-hidden">
        <SectionHeader label={t(labelKey)} title={doc.title} />
        <p style={{
          fontFamily: "var(--font-space-grotesk), 'Space Grotesk', serif",
          fontSize: 'clamp(0.9rem, 0.85rem + 0.5vw, 1rem)',
          color: 'var(--text-muted)',
          textAlign: 'center',
          maxWidth: '640px',
          margin: '0 auto 2rem',
          lineHeight: 1.7,
        }}>
          {doc.description}
        </p>
      </section>

      <div className="flex gap-10 max-lg:block">
        {showToc && <TableOfContents headings={doc.headings} />}
        <div className="flex-1 min-w-0">
          <DocsMarkdown body={doc.body} />

          <p style={{ marginTop: '2.5rem', fontFamily: monoFont, fontSize: '12px', color: 'var(--text-muted)' }}>
            {t('shell.docPage.source')}{' '}
            <a href={REPO_BLOB + doc.source} target="_blank" rel="noreferrer" className="link-underline" style={{ color: 'var(--accent-blue)' }}>
              {doc.source}
            </a>
          </p>
        </div>
      </div>
    </div>
  )
}

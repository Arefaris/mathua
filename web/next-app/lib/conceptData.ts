import conceptsData from '../data/concepts.json'
import ruLabels from '../data/concepts.labels.ru.json'
import ukLabels from '../data/concepts.labels.uk.json'
import { getRenderLocale, type Locale } from './i18n/locale'

// Typed view over data/concepts.json. The raw JSON import infers a large
// literal type that is awkward to iterate, which previously forced `as any[]`
// casts at every call site. One named contract here keeps callers typed.
export interface ConceptRecord {
  id: string
  label: string
  domain: string
  subdomain?: string
  grading_type?: string
  prerequisites?: string[]
  mastery_threshold?: { streak: number; avg_time_seconds: number }
  /** Set when the lesson's licence requires a fixed attribution on every page view. */
  lesson_credit?: string
}

// Translated labels per language, id -> label, generated by scripts/build-graph.mjs from the
// content side's overlays. `{}` when there is none, which leaves every label English.
const translatedLabels: Partial<Record<Locale, Record<string, string>>> = {
  ru: ruLabels as Record<string, string>,
  uk: ukLabels as Record<string, string>,
}

/**
 * The corpus with a `label` that follows the language.
 *
 * Roughly fifteen places read `concept.label` from this bundled copy: the learn stepper, the
 * graph, the domain table, the share report. Making `label` a getter changes them all at once
 * and leaves each call site as it was; the alternative was threading a lookup through every one
 * of them. The records are copies, so the imported JSON is not touched. A component picks up a
 * switch because the page remounts (see LocaleRoot), and a first load in Russian because the
 * component also subscribes to the locale through `useT`.
 */
export const concepts: ConceptRecord[] = (conceptsData as ConceptRecord[]).map(c => {
  const record = { ...c }
  const english = c.label
  Object.defineProperty(record, 'label', {
    enumerable: true,
    get: () => translatedLabels[getRenderLocale()]?.[c.id] ?? english,
  })
  return record
})
